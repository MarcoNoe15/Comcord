-- =====================================================================
-- Comcord — esquema da base de dados (Supabase / PostgreSQL)
-- Pode ser corrido no projeto do AdegaPlan: todas as tabelas do Comcord
-- têm o prefixo cc_ e não tocam nas tabelas existentes.
-- Pode ser corrido de novo sem problema (usa "if not exists").
-- Inclui RLS + política anon e os GRANTs explícitos (obrigatórios
-- em tabelas novas do schema public desde 30/10/2026).
-- =====================================================================

create table if not exists public.cc_departamentos (
  id          bigint generated by default as identity primary key,
  nome        text not null unique,
  ativo       boolean not null default true,
  created_at  timestamptz not null default now()
);

create table if not exists public.cc_pessoas (
  id              bigint generated by default as identity primary key,
  nome            text not null,
  departamento_id bigint references public.cc_departamentos(id) on delete set null,
  email           text,
  ativo           boolean not null default true,
  created_at      timestamptz not null default now()
);

create table if not exists public.cc_topicos (
  id                      bigint generated by default as identity primary key,
  ref                     text unique,                         -- TOP-2026-001
  titulo                  text not null,
  descricao               text,
  estado                  text not null default 'Aberto'
                          check (estado in ('Aberto','Em curso','Fechado')),
  prioridade              text not null default 'Média'
                          check (prioridade in ('Baixa','Média','Alta')),
  criado_por              text,                                -- texto livre
  departamento_origem_id  bigint references public.cc_departamentos(id) on delete set null,
  responsavel             text,                                -- quem executa (texto livre)
  departamento_resp_id    bigint references public.cc_departamentos(id) on delete set null,
  data_inicio             date default current_date,
  data_fim                date,
  created_at              timestamptz not null default now(),
  updated_at              timestamptz not null default now()
);

-- Atas: uma linha por reunião
create table if not exists public.cc_reunioes (
  id             bigint generated by default as identity primary key,
  ref            text unique,                                  -- ATA-2026-001
  data           date not null default current_date,
  titulo         text,
  local          text,
  participantes  text,                                         -- nomes separados por vírgula
  notas          text,
  proxima_data   date,
  created_at     timestamptz not null default now(),
  updated_at     timestamptz not null default now()
);

-- Tópicos discutidos em cada reunião
create table if not exists public.cc_reuniao_topicos (
  id          bigint generated by default as identity primary key,
  reuniao_id  bigint not null references public.cc_reunioes(id) on delete cascade,
  topico_id   bigint not null references public.cc_topicos(id)  on delete cascade,
  created_at  timestamptz not null default now(),
  unique (reuniao_id, topico_id)
);

-- Observações / follow-up (as que vêm de uma ata têm reuniao_id)
create table if not exists public.cc_observacoes (
  id          bigint generated by default as identity primary key,
  topico_id   bigint not null references public.cc_topicos(id) on delete cascade,
  reuniao_id  bigint references public.cc_reunioes(id) on delete set null,
  data        date not null default current_date,
  autor       text,
  texto       text not null,
  created_at  timestamptz not null default now()
);
-- caso a tabela observacoes já exista de uma versão anterior:
alter table public.cc_observacoes add column if not exists reuniao_id bigint references public.cc_reunioes(id) on delete set null;

create index if not exists cc_idx_topicos_estado   on public.cc_topicos(estado);
create index if not exists cc_idx_topicos_dep_resp on public.cc_topicos(departamento_resp_id);
create index if not exists cc_idx_obs_topico       on public.cc_observacoes(topico_id);
create index if not exists cc_idx_obs_reuniao      on public.cc_observacoes(reuniao_id);
create index if not exists cc_idx_rt_reuniao       on public.cc_reuniao_topicos(reuniao_id);

-- ---------------------------------------------------------------------
-- RLS + política permissiva para a chave anon (mesmo modelo do MANGEST)
-- ---------------------------------------------------------------------
do $$
declare t text;
begin
  foreach t in array array['cc_departamentos','cc_pessoas','cc_topicos','cc_reunioes','cc_reuniao_topicos','cc_observacoes'] loop
    execute format('alter table public.%I enable row level security', t);
    execute format('drop policy if exists allow_all_anon on public.%I', t);
    execute format('create policy allow_all_anon on public.%I for all to anon using (true) with check (true)', t);
    execute format('grant select, insert, update, delete on public.%I to anon', t);
  end loop;
end $$;

grant usage on schema public to anon;
grant usage, select on all sequences in schema public to anon;

